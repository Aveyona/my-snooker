/** Doplní chýbajúce hindské názvy lekcií a texty scén. */
function mysn_tut_fill_hi( $lessons ) {
	$hi = mysn_tut_hi();
	foreach ( $lessons as &$l ) {
		if ( empty( $l['title_hi'] ) && isset( $hi['titles'][ $l['id'] ] ) ) {
			$l['title_hi'] = $hi['titles'][ $l['id'] ];
		}
		foreach ( (array) ( $l['scenes'] ?? array() ) as $i => $s ) {
			if ( empty( $s['text_hi'] ) && isset( $hi['texts'][ $l['id'] ][ $s['id'] ] ) ) {
				$l['scenes'][ $i ]['text_hi'] = $hi['texts'][ $l['id'] ][ $s['id'] ];
			}
		}
	}
	unset( $l );
	return $lessons;
}
